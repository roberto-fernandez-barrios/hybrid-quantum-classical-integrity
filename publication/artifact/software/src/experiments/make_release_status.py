"""Generate the single source of truth for release counts (artifact 1.2.0).

Every count that documentation quotes (evidence manifests, manifested outputs,
artifact files, tests, main and supplement page counts, PDF hashes, version,
DOIs) is computed here from the repository state and written to
``publication/RELEASE_STATUS.md`` and ``publication/RELEASE_STATUS.json``.
Documentation must cite this file instead of repeating numbers. Nothing in
the file is typed by hand.

Usage (repository root, after the build, the artifact assembly and the tests):

    .venv/Scripts/python.exe -m src.experiments.make_release_status
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import subprocess
import sys
from datetime import date
from pathlib import Path

from src.experiments.verify_publication_artifact import verify


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def _pdf_pages(path: Path) -> int | None:
    try:
        out = subprocess.run(["pdfinfo", str(path)], capture_output=True, text=True, check=True).stdout
    except (OSError, subprocess.CalledProcessError):
        return None
    match = re.search(r"^Pages:\s+(\d+)", out, re.M)
    return int(match.group(1)) if match else None


def _test_count(repo: Path) -> int:
    """Count collected tests without running them (pytest --collect-only)."""

    out = subprocess.run([sys.executable, "-m", "pytest", "--collect-only", "-q", "-p", "no:cacheprovider", "tests"], cwd=repo, capture_output=True, text=True)
    match = re.search(r"(\d+) tests? collected", out.stdout + out.stderr)
    if match:
        return int(match.group(1))
    lines = [line for line in out.stdout.splitlines() if "::" in line]
    return len(lines)


def _doi_fields(repo: Path) -> dict[str, str]:
    text = (repo / "CITATION.cff").read_text(encoding="utf-8")
    version_doi = re.search(r'^doi:\s*"([^"]+)"', text, re.M)
    concept = re.search(r'value:\s*"(10\.5281/zenodo\.\d+)"\s*\n\s*description:\s*"Concept DOI', text)
    return {
        "version_doi": version_doi.group(1) if version_doi else "",
        "concept_doi": concept.group(1) if concept else "",
    }


def build(repo: Path) -> dict[str, object]:
    version = (repo / "VERSION").read_text(encoding="utf-8").strip()
    artifact = repo / "publication" / "artifact"
    summary = verify(artifact) if artifact.exists() else {}
    main_pdf = repo / "output/pdf/paper15_tdsc_submission.pdf"
    supp_pdf = repo / "output/pdf/paper15_tdsc_supplement.pdf"
    status = {
        "generated_on": date.today().isoformat(),
        "version": version,
        "artifact_version": (artifact / "VERSION").read_text(encoding="utf-8").strip() if (artifact / "VERSION").exists() else "",
        "evidence_manifests": summary.get("manifests"),
        "manifested_outputs": summary.get("manifested_outputs"),
        "artifact_files": summary.get("release_files"),
        "tests_collected": _test_count(repo),
        "main_pages": _pdf_pages(main_pdf),
        "supplement_pages": _pdf_pages(supp_pdf),
        "main_pdf_sha256": _sha256(main_pdf) if main_pdf.exists() else "",
        "supplement_pdf_sha256": _sha256(supp_pdf) if supp_pdf.exists() else "",
        "primary_counts": {k: v for k, v in summary.items() if k not in ("manifests", "manifested_outputs", "release_files")},
        **_doi_fields(repo),
    }
    return status


def render(status: dict[str, object]) -> str:
    counts = status["primary_counts"]
    lines = [
        f"# Release status — artifact {status['version']} (generated {status['generated_on']})",
        "",
        "Generated by `src/experiments/make_release_status.py`; do not edit by hand.",
        "Every document that quotes a count cites this file.",
        "",
        "| Quantity | Value |",
        "|---|---|",
        f"| Repository version (`VERSION`) | {status['version']} |",
        f"| Compact artifact version (`publication/artifact/VERSION`) | {status['artifact_version']} |",
        f"| Evidence manifests verified | {status['evidence_manifests']} |",
        f"| Manifested outputs verified | {status['manifested_outputs']} |",
        f"| Files in `ARTIFACT_MANIFEST.sha256` | {status['artifact_files']} |",
        f"| Tests collected (`pytest --collect-only`) | {status['tests_collected']} |",
        f"| Main article pages | {status['main_pages']} |",
        f"| Supplement pages | {status['supplement_pages']} |",
        f"| Main PDF SHA-256 | `{status['main_pdf_sha256']}` |",
        f"| Supplement PDF SHA-256 | `{status['supplement_pdf_sha256']}` |",
        f"| Version DOI (`CITATION.cff`) | {status['version_doi'] or 'not yet minted'} |",
        f"| Concept DOI | {status['concept_doi']} |",
        "",
        "## Primary counts recomputed by the verifier",
        "",
        "| Claim | Value |",
        "|---|---|",
    ]
    for key in sorted(counts):
        lines.append(f"| `{key}` | {counts[key]} |")
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo-root", type=Path, default=Path("."))
    args = parser.parse_args()
    repo = args.repo_root.resolve()
    status = build(repo)
    (repo / "publication" / "RELEASE_STATUS.json").write_text(json.dumps(status, indent=2), encoding="utf-8")
    (repo / "publication" / "RELEASE_STATUS.md").write_text(render(status), encoding="utf-8", newline="\n")
    print(json.dumps(status, indent=2))


if __name__ == "__main__":
    main()
